type Window = Literal["instant", "acc", "run", "avg", "max", "min"]


class VariableDefinition(FrozenBaseModel):
    name: str
    element: str
    level: str
    attrs: DataVarAttrs
    family: RrfsSourceFamily = "2dfld"
    group: Group = ROOT
    window: Window = "instant"
    selectors: tuple[str, ...] = ()
    alternatives: tuple[str, ...] = ()
    filters: tuple[CodecConfig, ...] = ()
    fill_value: float = np.nan
    hour_0: bool = True
    supported_leads: tuple[int, ...] | None = None


def data_vars(
    dims: Dims, *, sub_hourly: bool, members: bool
) -> Sequence[NoaaRrfsDataVar]:
    selected = (
        _SUB_HOURLY_NAMES
        if sub_hourly
        else _MEMBER_NAMES
        if members
        else {
            v.name if v.group is ROOT else f"{v.group}/{v.name}"
            for v in VARIABLE_DEFINITIONS
        }
    )
    result = []
    for definition in VARIABLE_DEFINITIONS:
        path = (
            definition.name
            if definition.group is ROOT
            else f"{definition.group}/{definition.name}"
        )
        if path not in selected:
            continue
        group = definition.group
        chunks = tuple(
            1059 if dim == "y" else 1799 if dim == "x" else 1 for dim in dims[group]
        )
        window = definition.window
        attrs = definition.attrs
        comment = attrs.comment or ""
        if window != "instant" and attrs.flag_values is None:
            sentence = (
                "Accumulated from the forecast initialization time to this step."
                if window == "run"
                else {
                    "acc": "Accumulated over the preceding hour.",
                    "avg": "Averaged over the preceding hour.",
                    "max": "Maximum value over the preceding hour.",
                    "min": "Minimum value over the preceding hour.",
                }[window]
            )
            attrs = replace(attrs, comment=" ".join(filter(None, (comment, sentence))))
        result.append(
            NoaaRrfsDataVar(
                name=definition.name,
                group=group,
                attrs=attrs,
                encoding=Encoding(
                    dtype="float64",
                    fill_value=definition.fill_value,
                    chunks=chunks,
                    shards=None,
                    compressors=(),
                    filters=definition.filters,
                    serializer=GribberishCodec(
                        var=definition.element,
                        adjust_longitude_range=True,
                        north_up=True,
                    ).to_dict(),
                ),
                internal_attrs=NoaaRrfsInternalAttrs(
                    source_family="subh" if sub_hourly else definition.family,
                    grib_element=definition.element,
                    grib_element_alternatives=definition.alternatives,
                    grib_description="",
                    index_position=0,
                    grib_index_level=definition.level,
                    grib_index_selectors=definition.selectors,
                    keep_mantissa_bits="no-rounding",
                    hour_0_values_override=definition.hour_0,
                    minimum_lead_time=pd.Timedelta(0)
                    if definition.hour_0
                    else pd.Timedelta("15min" if sub_hourly else "1h"),
                    supported_lead_times=None
                    if definition.supported_leads is None
                    else tuple(
                        pd.Timedelta(hours=h) for h in definition.supported_leads
                    ),
                    window_reset_frequency=pd.Timedelta.max
                    if window == "run"
                    else pd.Timedelta("1h")
                    if window != "instant"
                    else None,
                ),
            )
        )
    return result


